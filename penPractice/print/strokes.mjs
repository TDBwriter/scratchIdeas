export function glyph(ch) { return G[ch] || G[ch.toUpperCase()] || { w: 0.5, strokes: [] }; }
export const LETTERS = Object.keys(G);
// Letter gap and word gap (in cap heights). Word gap ≈ the width of a lowercase "o".
export const GAP = { letter: 0.18, word: 0.55 };
// Total advance of a string, in cap heights.
export function advance(text) {
  let w = 0;
  for (const ch of text) w += ch === ' ' ? GAP.word : glyph(ch).w + GAP.letter;
  return w;
}
